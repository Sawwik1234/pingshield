package com.sawwik.pingshield;

import java.util.Set;

/**
 * Защита замороженного игрока от среды: удушье под водой и удушье внутри блока
 * (упавший песок или гравий, обвал, поршень, чужая постройка).
 *
 * <p><b>Почему это нужно.</b> Пока игрок заморожен, он не может ни всплыть, ни выкопаться.
 * Урон от удушья плагин и так отменяет ({@code EntityDamageEvent} без исключений DROWNING и
 * SUFFOCATION в {@code damage.incoming.exceptions}), но остаются две проблемы:</p>
 * <ul>
 *   <li><b>Под водой</b> у него кончается запас воздуха: пузырьки на клиенте пустеют, играет
 *       звук захлёбывания, а после разморозки игрок всплывает уже с нулём воздуха и умирает —
 *       и это выглядит как «защита убила меня». Плюс нынешняя логика удержания считает
 *       «кончается воздух под водой» опасным местом и продлевает заморозку — то есть держит
 *       игрока под водой ещё дольше.</li>
 *   <li><b>В песке или гравии</b> игрок остаётся внутри блока: пока защита держит, это
 *       безопасно (урон отменяется), но в момент снятия защиты он начинает задыхаться и умирает,
 *       потому что выкопаться не успевает.</li>
 * </ul>
 *
 * <p><b>Решение:</b> воздух держим полным, пока игрок заморожен, и возвращаем его при
 * разморозке (как {@code restore-food} для сытости); а из блока перед снятием защиты выталкиваем
 * вверх — в ближайшее свободное место той же колонки, не дальше {@code escape-search-blocks}.</p>
 *
 * <p>Логика поиска вынесена сюда чистой функцией (колонка блоков приходит интерфейсом), поэтому
 * её можно проверить тестами без запуска сервера.</p>
 */
public final class EnvironmentGuard {

    /** Свободное место в колонке не найдено. */
    public static final int NOT_FOUND = Integer.MIN_VALUE;

    private EnvironmentGuard() {
    }

    /** Доступ к блокам одной вертикальной колонки (для тестов — обычная карта высот). */
    public interface Column {

        /**
         * Можно ли стоять на этой высоте: свободны и блок для ног, и блок для головы.
         * Вода и высокая трава «свободны» (в них не задыхаются), песок, гравий, камень — нет.
         */
        boolean free(int y);
    }

    /** Игрок внутри блока (засыпан песком/гравием, замурован, залит бетоном). */
    public static boolean isBuried(Column column, int y) {
        return !column.free(y);
    }

    /**
     * Высота, на которую нужно поднять игрока, чтобы выпустить его из блока.
     *
     * @param startY высота ног игрока
     * @param maxUp  сколько блоков вверх разрешено искать
     * @return {@code startY}, если игрок и так не в блоке; высоту свободного места;
     *         {@link #NOT_FOUND}, если в пределах {@code maxUp} места нет
     */
    public static int findEscapeY(int startY, int maxUp, Column column) {
        if (column.free(startY)) {
            return startY;
        }
        for (int y = startY + 1; y <= startY + maxUp; y++) {
            if (column.free(y)) {
                return y;
            }
        }
        return NOT_FOUND;
    }

    /**
     * Полные кубы, в которых, тем не менее, не задыхаются: порошковый снег (в нём тонут),
     * паутина и строительные леса (вязнут), снежный слой. Список по именам материалов, а не по
     * объектам — так проверка остаётся чистой и тестируемой: {@code Material#isSolid()} в 26.x
     * ходит в живой реестр сервера, и в тестах без сервера его не вызвать.
     */
    private static final Set<String> SOFT_FULL_CUBES = Set.of(
            "POWDER_SNOW", "COBWEB", "SCAFFOLDING", "SNOW", "MUD", "HONEY_BLOCK");

    /**
     * Твёрдый блок, в котором задыхаются: полноразмерный куб и не «мягкий». Песок, гравий, камень,
     * стекло — да; ковёр, ступени, плита, вода, трава — нет (в них стоят, а не «внутри» их).
     * Проверка специально строгая: ложное «засыпан» означало бы лишний подъём игрока
     * при каждой разморозке.
     *
     * @param solid        блок имеет коллизию ({@code Material#isSolid})
     * @param fullCube     его коллизия — полный куб 1x1x1
     * @param materialName {@code Material#name()} — по нему отсекаем «мягкие» полные кубы
     */
    public static boolean suffocating(boolean solid, boolean fullCube, String materialName) {
        return solid && fullCube && materialName != null && !SOFT_FULL_CUBES.contains(materialName);
    }

    /**
     * Нужно ли долить воздух. Пока игрок заморожен, запас держим полным: иначе клиент показывает
     * пустеющие пузырьки, а после разморозки игрок всплывает с нулём воздуха.
     */
    public static boolean shouldRefillAir(boolean keepAir, int remainingAir, int maxAir) {
        return keepAir && maxAir > 0 && remainingAir < maxAir;
    }

    /**
     * Воздух, который должен быть у игрока: полный — и во время заморозки, и в момент
     * разморозки (иначе он задохнётся в первую же секунду, хотя всё это время не мог всплыть).
     */
    public static int airAfterFreeze(boolean keepAir, int currentAir, int maxAir) {
        if (!keepAir || maxAir <= 0) {
            return currentAir;
        }
        return Math.max(currentAir, maxAir);
    }
}
